// Writes the ClassBench native module with N `Class()` definitions.
// Usage: node scripts/gen-classes.mjs [N]   (N defaults to $CLASS_COUNT, then 200)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const n = Number(process.argv[2] ?? process.env.CLASS_COUNT ?? 200);
if (!Number.isInteger(n) || n < 0) {
  console.error(`N must be a non-negative integer, got ${process.argv[2] ?? process.env.CLASS_COUNT}`);
  process.exit(1);
}

const moduleDir = fileURLToPath(new URL('../modules/class-bench/', import.meta.url));
const header = '// Generated by scripts/gen-classes.mjs. Do not edit.';

// The Swift module DSL has no loop support, so every class is its own line.
const swiftClasses = Array.from({ length: n }, (_, i) => `    Class("Bench${i}") {}`).join('\n');
writeFileSync(
  `${moduleDir}ios/ClassBenchModule.swift`,
  `${header}
import ExpoModulesCore

public class ClassBenchModule: Module {
  public func definition() -> ModuleDefinition {
    Name("ClassBench")

    Constant("classCount") { ${n} }

    // Lets scripts/bench.sh read the first screen's state from the system log.
    Function("report") { (message: String) in
      NSLog("classbench: %@", message)
    }
${swiftClasses ? `\n${swiftClasses}\n` : ''}  }
}
`
);

// Kotlin's `Class` is inline, so a loop keeps the method under the JVM size limit.
writeFileSync(
  `${moduleDir}android/src/main/java/expo/modules/classbench/ClassBenchModule.kt`,
  `${header}
package expo.modules.classbench

import android.util.Log
import expo.modules.kotlin.modules.Module
import expo.modules.kotlin.modules.ModuleDefinition

private const val CLASS_COUNT = ${n}

class ClassBenchModule : Module() {
  override fun definition() = ModuleDefinition {
    Name("ClassBench")

    Constant("classCount") { CLASS_COUNT }

    // Lets scripts/bench.sh read the first screen's state from logcat.
    Function("report") { message: String -> Log.i("ClassBench", "classbench: $message") }

    repeat(CLASS_COUNT) { Class("Bench$it") }
  }
}
`
);

console.log(`ClassBench now defines ${n} classes`);
